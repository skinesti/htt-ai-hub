// Build step: embeds the signed-in app files into the function bundle so they are never in the public folder.
import { mkdirSync, writeFileSync } from 'node:fs';
import { readShell } from './shell-files.js';

const out = new URL('../server/generated/', import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(new URL('shell.js', out), '// Generated by scripts/build-shell.js. Do not edit.\nexport default ' + JSON.stringify(readShell(), null, 1) + ';\n');
console.log('Built server/generated/shell.js');
